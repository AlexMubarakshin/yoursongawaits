# ---------- 7. seasonality ----------
P('## 7. Seasonality (SV trend Nov-2024 → Oct-2026)\n')
def peaks(series, n=3):
    idx = sorted(range(24), key=lambda i: -series[i])[:n]
    return ', '.join(f'{MONTHS[i]} ({series[i]:,.0f})' for i in sorted(idx))
def index(series):
    m = statistics.mean(series) or 1
    return ' '.join(f'{100*x/m:.0f}' for x in series)
P('Gift-intent volume by tier — monthly index (100 = 24-mo mean), Nov-24 … Oct-26:\n')
P('| Tier | peak months (abs. vol) | monthly index |')
P('|---|---|---|')
for t in order:
    s = a['tier_trend'].get(t)
    if s and sum(s) > 0:
        P(f'| {t} | {peaks(s)} | {index(s)} |')
P('\nAI-generator volume by tier (for markets with no gift data):\n')
P('| Tier | peak months | last-12 vs prior-12 |')
P('|---|---|---|')
for t in order:
    s = a['tier_trend_ai'].get(t)
    if s and sum(s) > 0:
        P(f'| {t} | {peaks(s)} | {100*(sum(s[12:])/sum(s[:12])-1):+.0f}% |')
P('\nOccasion peaks by country (OCCASION_* incl. the listening variants, which share the same seasonality):\n')
P('| Occasion | Country | 24-mo vol | peak months |')
P('|---|---|---:|---|')
ot = a['occ_trend']
for occ in ['mothers_day', 'fathers_day', 'anniversary', 'memorial', 'wedding']:
    items = sorted([(k.split('|')[1], v) for k, v in ot.items() if k.split('|')[0] == occ], key=lambda x: -sum(x[1]))[:8 if occ in ('mothers_day', 'fathers_day') else 4]
    for cc, s in items:
        if sum(s) > 0:
            P(f'| {occ} | {cc.upper()} | {sum(s):,.0f} | {peaks(s, 2)} |')
P('\nBirthday-name / GIFT_CORE by tier:\n')
P('| Cluster | Tier | peak months | index |')
P('|---|---|---|---|')
for cl in ['BIRTHDAY_NAME', 'GIFT_CORE', 'BRAND_COMPETITOR']:
    for t in ['EN_HIGH_CPC', 'EN_LOW_CPC']:
        s = a['bday_trend'].get(f'{cl}|{t}')
        if s and sum(s) > 0:
            P(f'| {cl} | {t} | {peaks(s)} | {index(s)} |')
P('\nNotes: US/CA/AU/IN/PH/ZA Mother\'s Day = 2nd Sunday of May; UK/IE = Mothering Sunday (March, 4th Sunday of Lent); Russia = last Sunday of November; '
  'Mexico & much of LatAm = 10 May; Brazil = 2nd Sunday of May; France = last Sunday of May (or June); Indonesia Hari Ibu = 22 Dec; Thailand = 12 Aug; Arab world = 21 Mar. '
  'Father\'s Day: 3rd Sunday of June in US/UK/CA/IN; first Sunday of Sept in AU/NZ; Germany = Ascension Day; Brazil = 2nd Sunday of August; RU has no mainstream Father\'s Day (23 Feb Defender of the Fatherland Day plays that role). '
  'Valentine\'s/Christmas gift-song volume is not measurable here (seeds missing) — US competitor data (Songfinch) shows Q4 and early Feb as peaks.\n')

